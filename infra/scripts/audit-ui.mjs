// Inventory only: source reachability is deliberately not called functional verification.
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = path => readFileSync(join(root, path), 'utf8');
function files(dir) {
  return readdirSync(join(root, dir), { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(`${dir}/${entry.name}`) : [`${dir}/${entry.name}`]);
}
const requirements = [];
for (const file of readdirSync(join(root, 'repomix/prompts')).filter(name => name.startsWith('batch-')).sort()) {
  const source = read(`repomix/prompts/${file}`);
  for (const match of source.matchAll(/^### (\d+)\. ([^\r\n]+)\r?\n\s*\*\*Final behavior:\*\* ([^\r\n]+)/gm)) {
    requirements.push({ id: Number(match[1]), title: match[2], behavior: match[3], source: file });
  }
}
const uiFiles = [...files('apps/shell/src'), ...files('apps/dashboard/src')].filter(path => /\.[jt]sx?$/.test(path));
const entries = uiFiles.filter(path => /\/(page|layout|error)\.tsx$/.test(path));
const reached = new Set();
function visit(path) {
  if (reached.has(path)) return;
  reached.add(path);
  const app = path.startsWith('apps/shell') ? 'apps/shell' : 'apps/dashboard';
  for (const match of read(path).matchAll(/(?:from\s*|import\s*\()\s*["']([^"']+)["']/g)) {
    const spec = match[1];
    if (!spec.startsWith('.') && !spec.startsWith('@/')) continue;
    const base = spec.startsWith('@/') ? join(root, app, 'src', spec.slice(2)) : resolve(root, dirname(path), spec);
    const target = ['', '.ts', '.tsx', '/index.ts', '/index.tsx'].map(ext => base + ext).find(p => existsSync(p) && /\.[jt]sx?$/.test(p));
    if (target) visit(relative(root, target).replaceAll('\\', '/'));
  }
}
entries.forEach(visit);
const orphaned = uiFiles.filter(path => path.includes('/components/') && path.endsWith('.tsx') && !reached.has(path));
const pages = entries.filter(path => path.endsWith('/page.tsx'));
const safe = value => value.replaceAll('|', '\\|');
const rows = requirements.map(item => `| ${item.id} | ${safe(item.title)} | ${safe(item.behavior)} | Not verified end to end |`).join('\n');
const out = `# UI feature inventory\n\nGenerated by \`node infra/scripts/audit-ui.mjs\`. Source: the 13 feature batches in \`repomix/prompts\`. The two update files refine these requirements, especially the self-hosted foundry, one assistant per space, and template/extension naming. Gemini hand-off instructions are not execution instructions for this audit.\n\nThis is a coverage inventory, not a claim that a feature works. Browser evidence and test results are recorded separately in [ui-feature-audit.md](ui-feature-audit.md).\n\n## Components without a route import path\n\n${orphaned.map(path => `- \`${path}\``).join('\n')}\n\nThese may be unused, obsolete, or missing a page connection. Reachable components can still be incomplete.\n\n## Pages to verify (${pages.length})\n\n${pages.map(path => `- [ ] \`${path}\``).join('\n')}\n\n## Feature requirements (${requirements.length})\n\n| # | Feature | Expected behavior | Verification |\n|---:|---|---|---|\n${rows}\n`;
writeFileSync(join(root, 'docs/ui-feature-inventory.md'), out);
console.log(JSON.stringify({ requirements: requirements.length, pages: pages.length, unreachableComponents: orphaned }, null, 2));
